#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# CNPG OpenShift Workshop - Scenario 02
# Explore PostgreSQL Cluster Resources
# -----------------------------------------------------------------------------

set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

source "${REPO_ROOT}/lib/ui.sh"

USER_NAME="$(oc whoami)"
NAMESPACE="workshop-${USER_NAME}"
CLUSTER_NAME="pg-${USER_NAME}"

show_instruct() {
  ui_note "
# 02 / Explore PostgreSQL Cluster

Explore the Kubernetes resources created and managed by
the EDB CloudNativePG operator.

## What you will learn
- Understand the PostgreSQL Cluster custom resource
- Identify primary and replica instances
- Explore PostgreSQL Services
- Understand persistent storage and WAL volumes
- Inspect PostgreSQL logs and Kubernetes events
- Discover PostgreSQL replication status

## Prerequisites
- Scenario 01 completed
- PostgreSQL cluster running with 3 instances

## Expected outcome
Understand how EDB CloudNativePG manages PostgreSQL
resources and replication on OpenShift.
"
  ui_pause
}

play() {

  ui_info "Select your workshop project"
  ui_command "oc project ${NAMESPACE}"
  ui_pause

  ui_info "Inspect PostgreSQL cluster status"
  ui_command "oc cnp status ${CLUSTER_NAME}"
  ui_pause

  ui_info "Identify PostgreSQL primary and replica instances"
  ui_command "oc get pods -l k8s.enterprisedb.io/cluster=${CLUSTER_NAME} -L k8s.enterprisedb.io/instanceRole -o wide"
  ui_pause

  ui_info "Explore PostgreSQL Services"
  ui_command "oc get services -l k8s.enterprisedb.io/cluster=${CLUSTER_NAME}"
  ui_pause

  ui_info "Inspect PostgreSQL read-write Services"
  ui_command "oc describe service ${CLUSTER_NAME}-rw"
  ui_pause

  ui_info "Inspect PostgreSQL read-only Services"
  ui_command "oc describe service ${CLUSTER_NAME}-ro"
  ui_pause

  ui_info "Explore PostgreSQL Secrets generated by the EDB operator"
  ui_command "oc get secrets -l k8s.enterprisedb.io/cluster=${CLUSTER_NAME}"
  ui_pause

  ui_info "Discover PostgreSQL application connection details"
  ui_command "oc get secret ${CLUSTER_NAME}-app -o json | jq -r '.data | {user, dbname, host, port} | with_entries(.value |= @base64d)'"
  ui_pause

  ui_info "Discover PostgreSQL connection string"
  ui_command "oc get secret ${CLUSTER_NAME}-app -o jsonpath='{.data.uri}' | base64 -d; echo"
  ui_pause

  ui_info "Explore PostgreSQL persistent storage"
  ui_command "oc get pvc -l k8s.enterprisedb.io/cluster=${CLUSTER_NAME} -o wide"
  ui_pause

  ui_info "Explore PostgreSQL instance logs"
  PRIMARY_POD="$(oc get cluster "${CLUSTER_NAME}" -o jsonpath='{.status.currentPrimary}')"
  [[ -n "${PRIMARY_POD}" ]] || { ui_error "No primary found"; return 1; }
  ui_command "oc logs ${PRIMARY_POD} -c postgres --tail=3 | jq"
  ui_pause

  ui_info "Verify PostgreSQL cluster health"
  ui_command "oc get cluster ${CLUSTER_NAME}"
  ui_pause

  ui_success "PostgreSQL cluster exploration completed."
  ui_info "Next scenario: 03_data_workload.sh"
}

main() {
  clear
  show_instruct
  play
}

main "$@"